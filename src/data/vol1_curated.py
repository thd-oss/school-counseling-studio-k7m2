def strip_html_tags(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()


def split_html_sentences_ko(raw_html):
    """Split HTML prose into complete Korean sentences without breaking tags, links, or decimals."""
    tokens = re.findall(r"<[^>]+>|[^<]+", raw_html)
    sentences = []
    cur_parts = []
    open_stack = []  # e.g. [("strong", "<strong>"), ("em", "<em>")]
    in_link = False

    def flush_cur():
        nonlocal cur_parts
        closing = "".join(f"</{tag}>" for tag, _ in reversed(open_stack))
        chunk = ("".join(cur_parts) + closing).strip()
        # Drop empty trailing whitespace-only tags
        if strip_html_tags(chunk):
            sentences.append({"html": chunk, "plain": strip_html_tags(chunk)})
        cur_parts = [open_tag for _, open_tag in open_stack]

    for tok in tokens:
        if tok.startswith("<"):
            cur_parts.append(tok)
            low = tok.lower()
            if low.startswith("<a "):
                in_link = True
            elif low == "</a>":
                in_link = False
            elif low == "<strong>":
                open_stack.append(("strong", "<strong>"))
            elif low == "<em>":
                open_stack.append(("em", "<em>"))
            elif low == "</strong>" and open_stack and open_stack[-1][0] == "strong":
                open_stack.pop()
            elif low == "</em>" and open_stack and open_stack[-1][0] == "em":
                open_stack.pop()
            continue

        if in_link:
            cur_parts.append(tok)
            continue

        # Split plain text segment on sentence enders followed by whitespace and Korean/English/bracket start
        parts = re.split(r"((?<=[다요까함임됨]\.)(?:[”’\)\]]?)\s+(?=[가-힣A-Za-z0-9「『“‘\(\[\*①②③④⑤]))", tok)
        if len(parts) == 1:
            cur_parts.append(tok)
        else:
            # parts alternates: seg0, sep0, seg1, sep1, ...
            i = 0
            while i < len(parts):
                seg = parts[i]
                if seg:
                    cur_parts.append(seg)
                if i + 1 < len(parts):
                    sep = parts[i + 1]
                    # Check if separator includes closing quote/paren before whitespace
                    m_trail = re.match(r"^([”’\)\]]+)\s+$", sep)
                    if m_trail:
                        cur_parts.append(m_trail.group(1))
                    flush_cur()
                i += 2

    flush_cur()
    return sentences


def extract_sub_key_terms(sub, max_terms=8):
    terms = []
    seen = set()
    for p in sub.get("paragraphs", []):
        if p.get("isCaption"):
            continue
        for m in re.finditer(r"<strong>([^<]{2,42})</strong>", p.get("html", "")):
            raw_t = html.unescape(m.group(1)).strip(" .:·,()")
            if not raw_t or raw_t in GENERIC_STRONG_SKIP or raw_t.startswith(("표 ", "[", "1)", "2)", "3)")):
                continue
            if re.search(r"[다요]\.$", raw_t):
                continue
            if raw_t not in seen:
                seen.add(raw_t)
                terms.append(raw_t)
                if len(terms) >= max_terms:
                    return terms
    # Supplement with legal statutes/models if fewer than 5 terms
    if len(terms) < 5:
        full_txt = " ".join(p["plain"] for p in sub.get("paragraphs", []) if not p.get("isCaption"))
        for k in extract_keywords_from_text(full_txt, max_kw=max_terms):
            if k not in seen:
                seen.add(k)
                terms.append(k)
                if len(terms) >= max_terms:
                    break
    return terms


def score_academic_sentence(s_plain, order_idx):
    score = 0
    if order_idx == 0:
        score += 4
    if re.search(r"(첫째|둘째|셋째|넷째|다섯째|①|②|③|④|핵심|원칙|정의|차이|변별|기준|모형|전략|단계|유의)", s_plain):
        score += 4
    if re.search(r"(「[^」]+」|제\d+조|N\s*=|d\s*=|%|\(\d{4}[a-z]?\))", s_plain):
        score += 3
    if 50 <= len(s_plain) <= 280:
        score += 2
    if len(s_plain) < 35:
        score -= 3
    return score


