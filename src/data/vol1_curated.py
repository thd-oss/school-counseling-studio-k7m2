def main():
    with open(RAW_PATH, "r", encoding="utf-8") as f:
        raw = json.load(f)

    for ch in raw["chapters"]:
        cno = ch["chapter"]
        ch["meta"] = CHAPTER_META[cno]
        ch["diagrams"] = DIAGRAM_DATA[cno]
        for sec in ch["coreSections"]:
            cur = CURATED_SECTIONS.get(sec["id"])
            if cur:
                sec["curated"] = cur
            else:
                sec["curated"] = {
                    "heroTakeaway": sec["introParagraphs"][0]["plain"][:140] if sec["introParagraphs"] else sec["title"],
                    "tags": [sub["title"][:16] for sub in sec["subsections"][:3]],
                    "bentoCards": [],
                }

    js_payload = (
        "/* Auto-generated Vol 1 Master Bundle for file:// standalone execution */\n"
        "window.__VOL1_DATA__ = "
        + json.dumps(raw, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    BUNDLE_PATH.write_text(js_payload, encoding="utf-8")
    size_kb = BUNDLE_PATH.stat().st_size / 1024
    print(f"[OK] Built {BUNDLE_PATH} ({size_kb:.1f} KB)")
    assert all(sec["curated"]["bentoCards"] for ch in raw["chapters"] for sec in ch["coreSections"]), "Missing curated card!"
    print("[OK] All 38 core sections curated + 6 interactive diagram datasets attached.")


if __name__ == "__main__":
    main()
